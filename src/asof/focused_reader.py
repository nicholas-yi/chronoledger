class Answer(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)
    value: str | None
    unit: str
    period: str
    evidence: str
    abstain: bool
    reason: str

    @model_validator(mode="after")
    def consistent(self):
        if self.abstain:
            if self.value is not None or any((self.unit, self.period, self.evidence)) or not self.reason.strip():
                raise ValueError("abstention requires null/empty fields and an explicit reason")
        else:
            if (self.value is None or not all(v.strip() for v in (
                    self.unit, self.period, self.evidence)) or self.reason):
                raise ValueError("answered fields must be complete, without an abstention reason")
            try:
                number = Decimal(self.value)
            except InvalidOperation as exc:
                raise ValueError("value must be a decimal string") from exc
            if not number.is_finite() or re.fullmatch(r"[0-9]{4}", self.period) is None:
                raise ValueError("finite value and explicit four-digit reporting year required")
        return self


class Critique(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)
    verdict: Literal["accept", "revise", "abstain"]
    issues: list[str]
    feedback: str

    @model_validator(mode="after")
    def consistent(self):
        if any(not issue.strip() for issue in self.issues):
            raise ValueError("critic issues must be nonempty")
        if self.verdict == "accept":
            if self.issues or self.feedback:
                raise ValueError("accept must not also request corrections")
        elif not self.issues or not self.feedback.strip():
            raise ValueError("nonaccept verdict requires issues and actionable feedback")
        return self


class CompactCritique(BaseModel):
    """V2 wire contract: bounded enums, never unconstrained generated feedback."""

    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)
    verdict: Literal["accept", "revise", "abstain"]
    issues: list[Issue] = Field(max_length=3)

    @model_validator(mode="after")
    def consistent(self):
        if len(set(self.issues)) != len(self.issues):
            raise ValueError("compact critic codes must be unique")
        if (self.verdict == "accept") != (not self.issues):
            raise ValueError("accept requires no codes; revise/abstain require an error code")
        return self

    def expanded(self) -> Critique:
        return Critique(verdict=self.verdict, issues=list(self.issues),
                        feedback=" ".join(ISSUE_FEEDBACK[issue] for issue in self.issues))


@dataclass(frozen=True)
class Case:
    id: str
    split: Literal["development", "evaluation"]
    category: str
    issuer: str
    metric: str
    requested_period: str
    source: str
    expected: tuple[str, str, str] | None
    probe: dict | None = None

    def public_input(self) -> dict:
        """Gold and split are deliberately absent from every model request."""
        return {"issuer": self.issuer, "metric": self.metric,
                "reporting_year": self.requested_period, "source": self.source}


def abstention(reason: str) -> Answer:
    return Answer(value=None, unit="", period="", evidence="", abstain=True, reason=reason)


def grounded(case: Case, answer: Answer) -> tuple[str, ...]:
    """Necessary token/quote checks, not semantic entailment or truth certification."""
    if answer.abstain:
        return ()
    errors = []
    quote = normalize(answer.evidence)
    if not quote or quote not in normalize(case.source):
        errors.append("evidence_not_verbatim")
    if normalize(case.issuer) not in quote:
        errors.append("issuer_not_in_evidence")
    if answer.period != case.requested_period or answer.period not in quote:
        errors.append("period_not_supported")
    if normalize(answer.unit) not in quote:
        errors.append("unit_not_in_evidence")
    numbers = re.findall(r"(?<![\w.])-?\d[\d,]*(?:\.\d+)?(?![\w.])", quote)
    if answer.value is None or not any(
            Decimal(number.replace(",", "")) == Decimal(answer.value) for number in numbers):
        errors.append("value_not_in_evidence")
    return tuple(errors)


def parser_answer(case: Case) -> Answer:
    """Deliberately narrow auditable grammar, not a general financial-language parser."""
    pattern = re.compile(
        rf"{re.escape(case.issuer)} reported {re.escape(case.metric)} of "
        rf"(?P<value>-?\d+(?:\.\d+)?) (?P<unit>[A-Za-z% ]+?) for "
        rf"{re.escape(case.requested_period)}\.", re.IGNORECASE)
    matches = list(pattern.finditer(case.source))
    values = {(Decimal(m["value"]), m["unit"].casefold()) for m in matches}
    if len(values) != 1:
        return abstention("parser_missing_or_conflicting_supported_grammar")
    match = matches[0]
    return Answer(value=match["value"], unit=match["unit"], period=case.requested_period,
                  evidence=match[0], abstain=False, reason="")


def messages(case: Case, stage: Literal["generate", "judge", "revise"], *,
             draft: str | None = None, critique: str | None = None,
             lessons: Sequence[str] = (), compact_critic: bool = False) -> list[dict]:
    payload = case.public_input()
    if stage != "generate":
        if draft is None:
            raise ValueError("critic/revision requires the actual draft")
        payload["draft"] = draft
    if stage == "revise":
        if critique is None:
            raise ValueError("revision requires the actual critique")
        payload["critic_feedback"] = critique
    if lessons:
        if stage == "generate" or len(lessons) > 6 or any(not item.strip() for item in lessons):
            raise ValueError("at most six verified development lessons for critic/revision only")
        payload["verified_development_lessons"] = list(lessons)
    system = {"generate": GENERATOR, "judge": CRITIC, "revise": REVISION}[stage]
    if compact_critic and stage == "judge":
        system = COMPACT_CRITIC
    return [{"role": "system", "content": system},
            {"role": "user", "content": json.dumps(payload, sort_keys=True)}]


def choose_final(case: Case, initial: Answer | None, revision: Answer | None) -> tuple[Answer, str]:
    """Never use expected/gold to choose an answer. One revision; otherwise valid draft or abstain."""
    if revision is not None and not grounded(case, revision):
        return revision, "revision_passed_necessary_grounding"
    if initial is not None and not grounded(case, initial):
        return initial, "retained_initial_no_verified_revision"
    return abstention("no_deterministically_grounded_output"), "neither_output_grounded"


def score(case: Case, answer: Answer | None) -> dict:
    if answer is None:
        return {"correct": False, "outcome": "invalid_response", "answered": False, "grounding": []}
    errors = grounded(case, answer)
    if answer.abstain:
        correct = case.expected is None
        outcome = "correct_abstention" if correct else "missed_answer"
    elif case.expected is None:
        correct, outcome = False, "answered_unanswerable"
    else:
        value, unit, period = case.expected
        correct = (answer.value is not None and Decimal(answer.value) == Decimal(value)
                   and normalize(answer.unit) == normalize(unit) and answer.period == period
                   and not errors)
        outcome = "correct_answer" if correct else "wrong_answer"
    return {"correct": correct, "outcome": outcome, "answered": not answer.abstain,
            "grounding": list(errors)}


def summarize(cases: Sequence[Case], records: dict[str, dict]) -> dict:
    """Missing/invalid cases remain in denominators; no selective-success fallback."""
    result = {}
    for split in ("development", "evaluation"):
        subset = [case for case in cases if case.split == split]
        result[split] = {}
        for arm in ARMS:
            values = [records.get(case.id, {}).get(arm) for case in subset]
            outcomes = [value["score"] if value else {
                "correct": False, "answered": False, "outcome": "not_attempted", "grounding": []}
                        for value in values]
            answered = sum(item["answered"] for item in outcomes)
            result[split][arm] = {
                "planned_cases": len(subset), "recorded_cases": sum(v is not None for v in values),
                "correct": sum(item["correct"] for item in outcomes),
                "wrong_answers": sum(item["answered"] and not item["correct"] for item in outcomes),
                "necessary_grounding_failures": sum(bool(item["grounding"]) for item in outcomes),
                "answered": answered,
                "coverage": answered/len(subset) if subset else None,
                "accuracy_all_planned": sum(item["correct"] for item in outcomes)/len(subset)
                if subset else None,
                "known_latency_seconds": sum(v["latency_seconds"] for v in values
                                             if v and v.get("latency_seconds") is not None),
                "missing_latency_records": sum(v is not None and v.get("latency_seconds") is None
                                               for v in values),
                "known_generated_tokens": sum(v["generated_tokens"] for v in values
                                              if v and v.get("generated_tokens") is not None),
                "outcomes": {name: sum(item["outcome"] == name for item in outcomes)
                             for name in sorted({item["outcome"] for item in outcomes})},
            }
    return result


def account_incomplete_attempts(
    cases: Sequence[Case], records: dict[str, dict], calls: Sequence[dict],
) -> dict[str, dict]:
    """Distinguish interrupted attempted arms from never-attempted ones, without inventing outputs."""
    result = deepcopy(records)
    for case in cases:
        attempted = {call["stage"] for call in calls if call["case_id"] == case.id}
        arms = result.setdefault(case.id, {}) if attempted else result.get(case.id, {})
        for arm, started in (
            ("single_pass", "generate" in attempted),
            ("judge_assisted", case.split == "evaluation" and "judge" in attempted),
        ):
            if started and arm not in arms:
                arms[arm] = {"answer": None, "score": score(case, None),
                             "reason": "attempted_but_not_completed; consult per-call receipts",
                             "latency_seconds": None, "generated_tokens": None}
    return result


def verified_error_bank(cases: Sequence[Case], records: dict[str, dict]) -> list[dict]:
    """Development-only invented known-answer fixes. Never turn judge opinion into a label."""
    errors = []
    for case in cases:
        if case.split != "development":
            continue
        record = records.get(case.id, {}).get("single_pass")
        if record is None or record["score"]["correct"]:
            continue
        errors.append({
            "case_id": case.id, "category": case.category,
            "input_sha256": hashlib.sha256(json.dumps(case.public_input(), sort_keys=True).encode()).hexdigest(),
            "observed_output": record.get("answer"), "expected_invented_tuple": case.expected,
            "verifier": "authored_invented_fixture_not_model_judge_or_human_gold",
            "proposal": "review retrieval/prompt against this development error; new freeze before change",
        })
    return errors


def development_lessons(errors: Sequence[dict]) -> tuple[str, ...]:
    """Frozen adaptation rule: select fixed critic reminders from verified development errors only."""
    rules = {
        "lookup_period": "Bind the value to the requested reporting year, not a nearby prior year.",
        "negative_value": "Preserve the explicit numeric sign; losses are not positive amounts.",
        "industry_not_issuer": "Industry metrics cannot establish the reporting issuer's metric.",
        "definition_mismatch": "A similarly named metric with a different definition is not the answer.",
        "percent_unit": "Preserve percentages and stated currency/scale; do not infer conversions.",
        "conflict": "Unreconciled equally authoritative conflicting values require abstention.",
    }
    if any(error.get("verifier") != "authored_invented_fixture_not_model_judge_or_human_gold"
           or not str(error.get("case_id", "")).startswith("D") for error in errors):
        raise ValueError("only machine-verified development fixture errors may supply lessons")
    categories = sorted({error["category"] for error in errors})
    if any(category not in rules for category in categories):
        raise ValueError("unknown error category; no automatic prompt invention")
    return tuple(rules[category] for category in categories)


def promotion_gate(cases: Sequence[Case], records: dict[str, dict], *, independent_audit: bool) -> dict:
    """Synthetic evidence can never self-promote a production pipeline, even with zero regressions."""
    evaluation = [case for case in cases if case.split == "evaluation"]
    corrected = regressed = 0
    complete = True
    for case in evaluation:
        arms = records.get(case.id, {})
        if any(arm not in arms for arm in ("single_pass", "judge_assisted")):
            complete = False
            continue
        old, new = (arms[a]["score"]["correct"] for a in ("single_pass", "judge_assisted"))
        corrected += not old and new
        regressed += old and not new
    return {
        "promote": False, "independent_audit_supplied": independent_audit,
        "reason": "this invented-case harness cannot authenticate independent semantic audit or promote",
        "evaluation_complete": complete and bool(evaluation),
        "corrected": corrected, "regressed": regressed,
        "candidate_for_independent_review": complete and bool(evaluation) and corrected > regressed,
        "weights_updated": False,
    }
